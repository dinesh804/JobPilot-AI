# 17. RANKING NODE
# ============================================================

def rank_jobs_node(
    state: AgentState
):

    print(
        "\n📊 Ranking jobs..."
    )


    jobs = state[
        "matched_jobs"
    ]


    # --------------------------------------------------------
    # Ranking
    # --------------------------------------------------------

    jobs.sort(
        key=lambda job: job.match_score,
        reverse=True
    )


    return {
        "matched_jobs": jobs
    }


