# 14. SEARCH JOBS NODE
# ============================================================

def search_node(
    state: AgentState
):

    print(
        "\n🔎 Searching jobs..."
    )

    candidate = state[
        "candidate"
    ]

    search_query = state[
        "search_query"
    ]


    # --------------------------------------------------------
    # Candidate location
    # --------------------------------------------------------

    location = (
        candidate
        .personal_info
        .location
        or "India"
    )


    print(
        f"Query    : {search_query}"
    )

    print(
        f"Location : {location}"
    )


    # --------------------------------------------------------
    # Call Adzuna
    # --------------------------------------------------------

    try:

        jobs = search_jobs(

            query=search_query,

            location=location,

            country="in",

            results_per_page=10
        )

    except Exception as e:

        print(
            f"❌ Job search failed: {e}"
        )

        return {
            "jobs": []
        }


    # --------------------------------------------------------
    # Remove duplicates
    # --------------------------------------------------------

    unique_jobs = []

    seen = set()

    for job in jobs:

        if job.url:

            key = (
                job.url
                .lower()
                .strip()
            )

        else:

            key = (
                f"{job.title.lower()}|"
                f"{job.company.lower()}|"
                f"{job.location.lower()}"
            )

        if key not in seen:

            seen.add(
                key
            )

            unique_jobs.append(
                job
            )


    print(
        f"Found {len(unique_jobs)} unique jobs"
    )


    return {
        "jobs": unique_jobs
    }


