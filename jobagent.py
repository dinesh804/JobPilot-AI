# 2. STRUCTURED OUTPUT SCHEMAS
# ============================================================

class JobAnalysis(BaseModel):

    experience_required: str = Field(
        default="Unknown",
        description=(
            "Experience requirement explicitly stated "
            "in the job description"
        )
    )

    experience_level: str = Field(
        default="Unknown",
        description=(
            "One of: Fresher, Entry Level, Junior, "
            "Mid Level, Senior, Lead, Unknown"
        )
    )

    required_skills: list[str] = Field(
        default_factory=list,
        description=(
            "Important technical skills explicitly "
            "required for the job"
        )
    )

    preferred_skills: list[str] = Field(
        default_factory=list,
        description=(
            "Preferred or nice-to-have skills"
        )
    )


class JobMatch(BaseModel):

    matching_skills: list[str] = Field(
        default_factory=list,
        description=(
            "Skills the candidate actually has "
            "that match the job"
        )
    )

    missing_skills: list[str] = Field(
        default_factory=list,
        description=(
            "Important skills explicitly required "
            "by the job that the candidate lacks"
        )
    )

    recommendation: str = Field(
        default="CONSIDER",
        description=(
            "One of APPLY, CONSIDER, or SKIP"
        )
    )

    recommendation_reason: str = Field(
        default="",
        description=(
            "Short explanation for the recommendation"
        )
    )


