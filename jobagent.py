# ============================================================
# 11. CALCULATE SKILL MATCHES
# ============================================================

def calculate_skill_matches(
    candidate_skills: list[str],
    job_skills: list[str]
) -> list[str]:

    matches = []

    for job_skill in job_skills:

        for candidate_skill in candidate_skills:

            if skills_match(
                candidate_skill,
                job_skill
            ):

                if job_skill not in matches:

                    matches.append(
                        job_skill
                    )

                break

    return matches


# ============================================================
# 12. CALCULATE MISSING SKILLS
# ============================================================

def calculate_missing_skills(
    candidate_skills: list[str],
    required_skills: list[str]
) -> list[str]:

    missing = []

    for required_skill in required_skills:

        found = False

        for candidate_skill in candidate_skills:

            if skills_match(
                candidate_skill,
                required_skill
            ):

                found = True
                break

        if not found:

            if required_skill not in missing:

                missing.append(
                    required_skill
                )

    return missing


# ============================================================
# 13. CALCULATE MATCH SCORE
# ============================================================

def calculate_match_score(
    candidate: CandidateProfile,
    job: Job
) -> float:

    """
    Calculate the numerical job match score
    using deterministic Python logic.

    Score:

    Required skills  : 50
    Preferred skills : 15
    Experience       : 15
    Role relevance   : 10
    Projects/Edu     : 10
    """

    candidate_skills = (
        get_candidate_skills(
            candidate
        )
    )

    required_skills = (
        job.required_skills
    )

    preferred_skills = (
        job.preferred_skills
    )


    # ========================================================
    # REQUIRED SKILLS — 50 POINTS
    # ========================================================

    if required_skills:

        required_matches = (
            calculate_skill_matches(
                candidate_skills,
                required_skills
            )
        )

        required_score = (
            len(required_matches)
            / len(required_skills)
        ) * 50

    else:

        required_score = 25


    # ========================================================
    # PREFERRED SKILLS — 15 POINTS
    # ========================================================

    if preferred_skills:

        preferred_matches = (
            calculate_skill_matches(
                candidate_skills,
                preferred_skills
            )
        )

        preferred_score = (
            len(preferred_matches)
            / len(preferred_skills)
        ) * 15

    else:

        preferred_score = 7.5


    # ========================================================
    # EXPERIENCE — 15 POINTS
    # ========================================================

    level = (
        job.experience_level
        or "Unknown"
    ).lower()

    experience_text = (
        job.experience_required
        or ""
    ).lower()

    candidate_has_experience = (
        len(candidate.experience) > 0
    )


    # Fresher / entry-level
    if any(
        keyword in level
        for keyword in [
            "fresher",
            "entry level",
            "junior",
            "graduate",
            "trainee"
        ]
    ):

        experience_score = 15


    # Senior / Lead without experience
    elif any(
        keyword in level
        for keyword in [
            "senior",
            "lead"
        ]
    ):

        if candidate_has_experience:

            experience_score = 15

        else:

            experience_score = 0


    # Unknown
    elif (
        not experience_text
        or experience_text == "unknown"
    ):

        experience_score = 10


    # Mid-level
    elif candidate_has_experience:

        experience_score = 15

    else:

        experience_score = 3


    # ========================================================
    # ROLE RELEVANCE — 10 POINTS
    # ========================================================

    target_roles = [
        normalize_skill(role)
        for role in candidate.target_roles
        if role
    ]

    job_title = normalize_skill(
        job.title
    )

    role_score = 0


    for role in target_roles:

        if (
            role in job_title
            or job_title in role
        ):

            role_score = 10

            break


    # Generic AI/ML relevance
    if role_score == 0:

        role_keywords = [

            "machine learning",

            "artificial intelligence",

            "ai engineer",

            "machine learning engineer",

            "ml engineer",

            "data scientist",

            "data science",

            "generative ai",

            "genai",

        ]

        if any(
            keyword in job_title
            for keyword in role_keywords
        ):

            role_score = 7

        else:

            role_score = 3


    # ========================================================
    # PROJECT / EDUCATION — 10 POINTS
    # ========================================================

    if candidate.projects:

        project_score = 10

    elif candidate.education:

        project_score = 7

    else:

        project_score = 3


    # ========================================================
    # FINAL SCORE
    # ========================================================

    score = (
        required_score
        + preferred_score
        + experience_score
        + role_score
        + project_score
    )


    # Clamp score
    score = max(
        0.0,
        min(
            100.0,
            score
        )
    )


    return round(
        score,
        1
    )


