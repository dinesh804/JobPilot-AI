# 16. MATCH JOBS NODE
# ============================================================

def match_jobs_node(
    state: AgentState
):

    print(
        "\n🎯 Matching jobs against candidate profile..."
    )

    candidate = state[
        "candidate"
    ]

    matched_jobs = []


    # --------------------------------------------------------
    # Candidate information
    # --------------------------------------------------------

    candidate_name = (
        candidate
        .personal_info
        .name
        or "Candidate"
    )


    candidate_location = (
        candidate
        .personal_info
        .location
        or "Not specified"
    )


    candidate_skills = (
        get_candidate_skills(
            candidate
        )
    )


    candidate_education = (
        get_candidate_education(
            candidate
        )
    )


    candidate_experience = (
        get_candidate_experience(
            candidate
        )
    )


    candidate_projects = (
        get_candidate_projects(
            candidate
        )
    )


    candidate_roles = (
        candidate.target_roles
        if candidate.target_roles
        else []
    )


    # --------------------------------------------------------
    # Match every job
    # --------------------------------------------------------

    jobs = state[
        "analyzed_jobs"
    ]


    for i, job in enumerate(
        jobs,
        start=1
    ):

        print(
            f"Matching {i}/{len(jobs)}: "
            f"{job.title} - {job.company}"
        )


        # ====================================================
        # PYTHON SKILL CALCULATION
        # ====================================================

        calculated_matching_skills = (
            calculate_skill_matches(
                candidate_skills,
                job.required_skills
                + job.preferred_skills
            )
        )


        calculated_missing_skills = (
            calculate_missing_skills(
                candidate_skills,
                job.required_skills
            )
        )


        # ====================================================
        # PYTHON SCORE
        # ====================================================

        score = calculate_match_score(
            candidate,
            job
        )


        # ====================================================
        # LLM MATCHING
        # ====================================================

        prompt = f"""
You are a professional AI job-matching assistant.

Compare the candidate with ONE job.

============================================================
CANDIDATE
============================================================

Name:
{candidate_name}

Location:
{candidate_location}

Education:
{candidate_education}

Professional Experience:
{candidate_experience}

Skills:
{candidate_skills}

Target Roles:
{candidate_roles}

Projects:
{candidate_projects}


============================================================
JOB
============================================================

Title:
{job.title}

Company:
{job.company}

Location:
{job.location}

Experience Required:
{job.experience_required}

Experience Level:
{job.experience_level}

Required Skills:
{job.required_skills}

Preferred Skills:
{job.preferred_skills}

Description:
{job.description or "Not available"}


============================================================
MATCHING TASK
============================================================

Identify:

1. Matching skills.
2. Missing important required skills.
3. Recommendation.
4. Short reason.


============================================================
IMPORTANT RULES
============================================================

- Only identify skills the candidate actually has.
- Do not invent candidate skills.
- Do not list every candidate skill as a missing skill.
- Only mark skills as missing if they are required by
  the job and are not present in the candidate profile.
- Preferred skills are NOT required skills.
- Consider equivalent names such as:
  Python = Python programming
  ML = Machine Learning
  GenAI = Generative AI
  Scikit Learn = scikit-learn
  Lang Chain = LangChain
  K8s = Kubernetes

Experience rules:

- Fresher, Graduate, Entry Level, Junior and Trainee
  positions can be recommended to candidates without
  professional experience.

- Senior and Lead positions should generally be SKIP
  for candidates without professional experience.

Recommendation must be exactly one of:

APPLY
CONSIDER
SKIP


APPLY:
Strong realistic fit.

CONSIDER:
Reasonable fit but meaningful gaps exist.

SKIP:
Major mismatch or unsuitable experience level.
"""


        try:

            result = match_llm.invoke(
                prompt
            )


            # =================================================
            # USE PYTHON-CALCULATED SKILLS
            # =================================================

            if calculated_matching_skills:

                job.matching_skills = (
                    calculated_matching_skills
                )

            else:

                job.matching_skills = (
                    result.matching_skills
                )


            if calculated_missing_skills:

                job.missing_skills = (
                    calculated_missing_skills
                )

            else:

                job.missing_skills = []


            # =================================================
            # SCORE
            # =================================================

            job.match_score = (
                score
            )


            # =================================================
            # RECOMMENDATION
            # =================================================

            recommendation = (
                result.recommendation
                .strip()
                .upper()
            )


            # -------------------------------------------------
            # Hard rule for senior jobs
            # -------------------------------------------------

            level = (
                job.experience_level
                or ""
            ).lower()


            candidate_has_experience = (
                len(candidate.experience) > 0
            )


            if (
                not candidate_has_experience
                and (
                    "senior" in level
                    or "lead" in level
                )
            ):

                recommendation = "SKIP"


            if recommendation not in {
                "APPLY",
                "CONSIDER",
                "SKIP"
            }:

                recommendation = (
                    "CONSIDER"
                )


            job.recommendation = (
                recommendation
            )


            # =================================================
            # REASON
            # =================================================

            reason = (
                result.recommendation_reason
                or ""
            ).strip()


            if not reason:

                reason = (
                    "Match evaluated using "
                    "skills, experience, role relevance, "
                    "education and projects."
                )


            job.recommendation_reason = (
                reason
            )


            matched_jobs.append(
                job
            )


        except Exception as e:

            print(
                f"⚠️ Matching failed: {e}"
            )


            # ------------------------------------------------
            # Still preserve Python score
            # ------------------------------------------------

            job.match_score = (
                score
            )


            job.matching_skills = (
                calculated_matching_skills
            )


            job.missing_skills = (
                calculated_missing_skills
            )


            job.recommendation = (
                "CONSIDER"
            )


            job.recommendation_reason = (
                "AI explanation failed, "
                "but the job was scored using "
                "the deterministic matching system."
            )


            matched_jobs.append(
                job
            )


    return {
        "matched_jobs":
            matched_jobs
    }


