# ============================================================
# 5. HELPER
# GET CANDIDATE SKILLS
# ============================================================

def get_candidate_skills(
    candidate: CandidateProfile
) -> list[str]:

    """
    Convert the nested Skills object into
    one flat list of unique skills.
    """

    skills = candidate.skills

    all_skills = (
        skills.programming
        + skills.machine_learning
        + skills.deep_learning
        + skills.genai
        + skills.frameworks
        + skills.databases
        + skills.cloud
        + skills.devops
        + skills.data_tools
        + skills.other
    )

    unique_skills = []

    seen = set()

    for skill in all_skills:

        if not skill:
            continue

        skill = skill.strip()

        if not skill:
            continue

        normalized = normalize_skill(
            skill
        )

        if normalized not in seen:

            seen.add(
                normalized
            )

            unique_skills.append(
                skill
            )

    return unique_skills


# ============================================================
# 6. SKILL NORMALIZATION
# ============================================================

def normalize_skill(
    skill: str
) -> str:

    """
    Normalize common variations of skills
    so that equivalent skills can match.
    """

    skill = (
        skill
        .lower()
        .strip()
    )

    skill = (
        skill
        .replace("_", " ")
        .replace("/", " ")
        .replace("-", " ")
    )

    skill = " ".join(
        skill.split()
    )

    aliases = {

        "sklearn":
            "scikit learn",

        "scikit learn":
            "scikit learn",

        "scikit learn library":
            "scikit learn",

        "ml":
            "machine learning",

        "machine learning":
            "machine learning",

        "ai":
            "artificial intelligence",

        "artificial intelligence":
            "artificial intelligence",

        "gen ai":
            "generative ai",

        "genai":
            "generative ai",

        "generative ai":
            "generative ai",

        "lang chain":
            "langchain",

        "langchain":
            "langchain",

        "vector db":
            "vector database",

        "vector databases":
            "vector database",

        "vector database":
            "vector database",

        "postgres":
            "postgresql",

        "postgresql":
            "postgresql",

        "mongo":
            "mongodb",

        "mongodb":
            "mongodb",

        "k8s":
            "kubernetes",

        "kubernetes":
            "kubernetes",

    }

    return aliases.get(
        skill,
        skill
    )


# ============================================================
# 7. CHECK SKILL MATCH
# ============================================================

def skills_match(
    candidate_skill: str,
    job_skill: str
) -> bool:

    """
    Determine whether two skills are equivalent
    or sufficiently similar.
    """

    candidate = normalize_skill(
        candidate_skill
    )

    job = normalize_skill(
        job_skill
    )

    # Exact match
    if candidate == job:
        return True

    # One contains the other
    if (
        candidate in job
        or job in candidate
    ):
        return True

    # Common mappings
    related_groups = [

        {
            "python",
            "python programming"
        },

        {
            "machine learning",
            "machine learning algorithms",
            "machine learning models"
        },

        {
            "deep learning",
            "deep learning models"
        },

        {
            "scikit learn",
            "scikit learn library"
        },

        {
            "pytorch",
            "torch"
        },

        {
            "tensorflow",
            "tensorflow keras"
        },

        {
            "generative ai",
            "genai",
            "generative artificial intelligence"
        },

        {
            "natural language processing",
            "nlp"
        },

        {
            "postgresql",
            "postgres"
        },

        {
            "mongodb",
            "mongo"
        },

        {
            "kubernetes",
            "k8s"
        },

    ]

    for group in related_groups:

        if (
            candidate in group
            and job in group
        ):

            return True

    return False


# ============================================================
# 8. GET EDUCATION
# ============================================================

def get_candidate_education(
    candidate: CandidateProfile
) -> str:

    education_list = []

    for education in candidate.education:

        parts = []

        if education.degree:

            parts.append(
                education.degree
            )

        if education.field_of_study:

            parts.append(
                education.field_of_study
            )

        if education.institution:

            parts.append(
                education.institution
            )

        if education.graduation_year:

            parts.append(
                education.graduation_year
            )

        if education.grade:

            parts.append(
                education.grade
            )

        if parts:

            education_list.append(
                " - ".join(parts)
            )

    if not education_list:

        return "Not available"

    return "\n".join(
        education_list
    )


# ============================================================
# 9. GET EXPERIENCE
# ============================================================

def get_candidate_experience(
    candidate: CandidateProfile
) -> str:

    experience_list = []

    for experience in candidate.experience:

        parts = []

        if experience.role:

            parts.append(
                experience.role
            )

        if experience.company:

            parts.append(
                experience.company
            )

        if experience.location:

            parts.append(
                experience.location
            )

        if experience.duration:

            parts.append(
                experience.duration
            )

        if experience.responsibilities:

            parts.append(
                "Responsibilities: "
                + "; ".join(
                    experience.responsibilities
                )
            )

        if parts:

            experience_list.append(
                " | ".join(parts)
            )

    if not experience_list:

        return (
            "No professional experience "
            "listed in the resume."
        )

    return "\n".join(
        experience_list
    )


